def lookup(mac: str) -> str:
    """
    Given a MAC address in any common format, return the manufacturer name
    or 'Unknown'.
    """
    if not mac:
        return "Unknown"
    # normalise: remove separators, uppercase, take first 6 hex chars
    clean = mac.upper().replace(":", "").replace("-", "").replace(".", "")
    oui   = clean[:6]
    return _OUI.get(oui, "Unknown")


